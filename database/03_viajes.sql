-- =====================================================================
-- D'Tulia · CAPA DE DATOS · 03 · Viajes del jefe
-- ---------------------------------------------------------------------
-- El jefe lleva mercadería del almacén (Trujillo) a otras ciudades, la
-- vende allá con comprobantes en papel y no tiene fecha fija de regreso.
-- Se controlan productos, no dinero:
--   fn_viaje_abrir         carga inicial         → SALIDA_VIAJE (resta del almacén)
--   fn_viaje_enviar        cajas o unidades que pide durante el viaje → SALIDA_VIAJE
--   fn_viaje_anular_envio  corrige un envío registrado por error      → RETORNO_VIAJE
--   fn_viaje_liquidar      al volver: vendido por ciudad, regresó y merma;
--                          lo que regresó vuelve al almacén (RETORNO_VIAJE)
--                          y el viaje queda cerrado
-- Diferencia = llevó − vendió − regresó − merma. Si no es 0, el viaje se
-- cierra igual pero exige una observación.
-- Las ventas del viaje NO pasan por comprobantes: ese stock ya salió del
-- almacén y el trigger de ventas lo descontaría dos veces.
-- Requiere 01 y 02. Es idempotente.
-- =====================================================================

set search_path = public, extensions;

-- ---------------------------------------------------------------------
-- 1. Tablas
-- ---------------------------------------------------------------------
create table if not exists public.viajes (
  viaje_id                integer generated by default as identity primary key,
  viaje_empleado_id       integer not null references public.empleados (empleado_id),
  viaje_fecha_salida      timestamptz not null default now(),
  viaje_estado            varchar(15) not null default 'ABIERTO'
                          constraint chk_viaje_estado check (viaje_estado in ('ABIERTO', 'LIQUIDADO')),
  viaje_fecha_liquidacion timestamptz,
  viaje_liquidado_por     integer references public.empleados (empleado_id),
  viaje_observacion       varchar(300)
);

-- Un solo viaje abierto a la vez: los pedidos del jefe se suman a ese viaje
create unique index if not exists uq_viajes_un_abierto on public.viajes ((true)) where viaje_estado = 'ABIERTO';
create index if not exists idx_viajes_empleado on public.viajes (viaje_empleado_id);
create index if not exists idx_viajes_liquidado_por on public.viajes (viaje_liquidado_por);

-- Envío 1 = carga inicial; 2, 3… = lo que el jefe pide durante el viaje
create table if not exists public.viaje_envios (
  envio_id          integer generated by default as identity primary key,
  envio_viaje_id    integer not null references public.viajes (viaje_id),
  envio_numero      integer not null,
  envio_sede_id     integer not null references public.sedes (sede_id),
  envio_referencia  varchar(100),
  envio_empleado_id integer not null references public.empleados (empleado_id),
  envio_fecha       timestamptz not null default now(),
  envio_anulado     boolean not null default false,
  constraint uq_viaje_envios_numero unique (envio_viaje_id, envio_numero)
);
create index if not exists idx_viaje_envios_sede on public.viaje_envios (envio_sede_id);
create index if not exists idx_viaje_envios_empleado on public.viaje_envios (envio_empleado_id);

create table if not exists public.viaje_envio_detalle (
  detalle_envio_id    integer not null references public.viaje_envios (envio_id),
  detalle_producto_id integer not null references public.productos (producto_id),
  detalle_cantidad    integer not null constraint chk_viaje_envio_cantidad check (detalle_cantidad > 0),
  primary key (detalle_envio_id, detalle_producto_id)
);
create index if not exists idx_viaje_envio_detalle_producto on public.viaje_envio_detalle (detalle_producto_id);

-- Lo vendido en cada ciudad (se registra al liquidar, según la hoja del jefe)
create table if not exists public.viaje_ventas (
  venta_viaje_id    integer not null references public.viajes (viaje_id),
  venta_sede_id     integer not null references public.sedes (sede_id),
  venta_producto_id integer not null references public.productos (producto_id),
  venta_cantidad    integer not null constraint chk_viaje_venta_cantidad check (venta_cantidad > 0),
  primary key (venta_viaje_id, venta_sede_id, venta_producto_id)
);
create index if not exists idx_viaje_ventas_sede on public.viaje_ventas (venta_sede_id);
create index if not exists idx_viaje_ventas_producto on public.viaje_ventas (venta_producto_id);

-- Lo que regresó al almacén y lo que se perdió (rotura, regalo…) por producto
create table if not exists public.viaje_retornos (
  retorno_viaje_id     integer not null references public.viajes (viaje_id),
  retorno_producto_id  integer not null references public.productos (producto_id),
  retorno_cantidad     integer not null default 0 constraint chk_viaje_retorno_cantidad check (retorno_cantidad >= 0),
  retorno_merma        integer not null default 0 constraint chk_viaje_retorno_merma check (retorno_merma >= 0),
  retorno_motivo_merma varchar(100),
  primary key (retorno_viaje_id, retorno_producto_id)
);
create index if not exists idx_viaje_retornos_producto on public.viaje_retornos (retorno_producto_id);

-- Sin políticas: solo el backend (rol postgres) accede, igual que al resto de tablas
alter table public.viajes              enable row level security;
alter table public.viaje_envios        enable row level security;
alter table public.viaje_envio_detalle enable row level security;
alter table public.viaje_ventas        enable row level security;
alter table public.viaje_retornos      enable row level security;

-- ---------------------------------------------------------------------
-- 2. Envíos (uso interno de fn_viaje_abrir y fn_viaje_enviar)
-- ---------------------------------------------------------------------
-- Valida destino, productos y stock, y bloquea los productos. Se llama antes
-- de crear el viaje para que un intento fallido no consuma su número.
-- p_items: [{"producto_id": 1, "cantidad": 24}, ...] en unidades
create or replace function public.fn_viaje_validar_envio(p_sede_id integer, p_items jsonb)
returns public.sedes
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_sede        sedes%rowtype;
  v_solicitados integer;
  v_existentes  integer;
  v_falta       record;
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'El envío debe incluir al menos un producto' using errcode = 'DT422';
  end if;
  if exists (select 1
               from jsonb_to_recordset(p_items) as x (producto_id integer, cantidad integer)
              where x.producto_id is null or x.cantidad is null or x.cantidad <= 0) then
    raise exception 'Cada producto del envío debe tener una cantidad mayor a 0' using errcode = 'DT422';
  end if;

  select * into v_sede from sedes where sede_id = p_sede_id;
  if not found then
    raise exception 'La ciudad % no existe', p_sede_id using errcode = 'DT404';
  end if;
  if v_sede.sede_es_almacen then
    raise exception 'El destino del viaje no puede ser el almacén (%)', v_sede.sede_nombre using errcode = 'DT422';
  end if;

  -- Productos: bloqueo en orden de id (evita deadlocks) y validación de stock
  select count(*) into v_solicitados
    from (select distinct x.producto_id from jsonb_to_recordset(p_items) as x (producto_id integer)) s;

  perform 1
     from productos p
    where p.producto_id in (select x.producto_id from jsonb_to_recordset(p_items) as x (producto_id integer))
    order by p.producto_id
      for update;
  get diagnostics v_existentes = row_count;

  if v_existentes <> v_solicitados then
    raise exception 'Uno o más productos del envío no existen' using errcode = 'DT404';
  end if;

  select p.producto_nombre || ' ' || pr.presentacion_nombre as producto_nombre,
         coalesce(p.producto_stock_actual, 0) as stock, i.cantidad
    into v_falta
    from (select x.producto_id, sum(x.cantidad)::integer as cantidad
            from jsonb_to_recordset(p_items) as x (producto_id integer, cantidad integer)
           group by x.producto_id) i
    join productos p       on p.producto_id = i.producto_id
    join presentaciones pr on pr.presentacion_id = p.producto_presentacion_id
   where coalesce(p.producto_stock_actual, 0) < i.cantidad
   order by p.producto_id
   limit 1;

  if found then
    raise exception 'Stock insuficiente en el almacén para "%": disponible %, solicitado %',
      v_falta.producto_nombre, v_falta.stock, v_falta.cantidad using errcode = 'DT409';
  end if;

  return v_sede;
end;
$$;

create or replace function public.fn_viaje_registrar_envio(
  p_viaje_id    integer,
  p_empleado_id integer,
  p_sede_id     integer,
  p_items       jsonb,
  p_referencia  varchar default null
) returns public.viaje_envios
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_sede   sedes%rowtype;
  v_numero integer;
  v_envio  viaje_envios%rowtype;
  v_item   record;
  v_ref    varchar;
begin
  v_sede := fn_viaje_validar_envio(p_sede_id, p_items);

  -- El llamador bloquea el viaje, así que el número no se repite
  select coalesce(max(envio_numero), 0) + 1 into v_numero from viaje_envios where envio_viaje_id = p_viaje_id;

  insert into viaje_envios (envio_viaje_id, envio_numero, envio_sede_id, envio_referencia, envio_empleado_id)
  values (p_viaje_id, v_numero, p_sede_id, upper(nullif(trim(p_referencia), '')), p_empleado_id)
  returning * into v_envio;

  insert into viaje_envio_detalle (detalle_envio_id, detalle_producto_id, detalle_cantidad)
  select v_envio.envio_id, x.producto_id, sum(x.cantidad)::integer
    from jsonb_to_recordset(p_items) as x (producto_id integer, cantidad integer)
   group by x.producto_id;

  v_ref := left(format('VIAJE #%s · %s → %s', p_viaje_id,
                       case when v_numero = 1 then 'CARGA INICIAL' else 'ENVÍO ' || v_numero end,
                       v_sede.sede_nombre), 100);

  for v_item in
    select detalle_producto_id, detalle_cantidad
      from viaje_envio_detalle
     where detalle_envio_id = v_envio.envio_id
     order by detalle_producto_id
  loop
    perform fn_mover_stock(v_item.detalle_producto_id, -v_item.detalle_cantidad, 'SALIDA_VIAJE', v_ref);
  end loop;

  return v_envio;
end;
$$;

-- ---------------------------------------------------------------------
-- 3. Abrir viaje (carga inicial) y enviar más mercadería
-- ---------------------------------------------------------------------
create or replace function public.fn_viaje_abrir(
  p_empleado_id integer,
  p_sede_id     integer,
  p_items       jsonb,
  p_referencia  varchar default null
) returns setof public.viajes
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_abierto integer;
  v_viaje   viajes%rowtype;
begin
  select viaje_id into v_abierto from viajes where viaje_estado = 'ABIERTO';
  if found then
    raise exception 'Ya hay un viaje abierto (#%). Registre lo que pide el jefe con "Enviar al viaje" o liquídelo antes de abrir otro',
      v_abierto using errcode = 'DT409';
  end if;

  perform fn_viaje_validar_envio(p_sede_id, p_items);
  insert into viajes (viaje_empleado_id) values (p_empleado_id) returning * into v_viaje;
  perform fn_viaje_registrar_envio(v_viaje.viaje_id, p_empleado_id, p_sede_id, p_items, p_referencia);

  return next v_viaje;
end;
$$;

create or replace function public.fn_viaje_enviar(
  p_viaje_id    integer,
  p_empleado_id integer,
  p_sede_id     integer,
  p_items       jsonb,
  p_referencia  varchar default null
) returns setof public.viaje_envios
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_viaje viajes%rowtype;
begin
  select * into v_viaje from viajes where viaje_id = p_viaje_id for update;
  if not found then
    raise exception 'El viaje % no existe', p_viaje_id using errcode = 'DT404';
  end if;
  if v_viaje.viaje_estado <> 'ABIERTO' then
    raise exception 'El viaje #% ya fue liquidado', p_viaje_id using errcode = 'DT409';
  end if;

  return next fn_viaje_registrar_envio(p_viaje_id, p_empleado_id, p_sede_id, p_items, p_referencia);
end;
$$;

-- Devuelve al almacén un envío registrado por error (solo con el viaje abierto)
create or replace function public.fn_viaje_anular_envio(p_envio_id integer)
returns setof public.viaje_envios
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_envio viaje_envios%rowtype;
  v_viaje viajes%rowtype;
  v_item  record;
  v_ref   varchar;
begin
  select * into v_envio from viaje_envios where envio_id = p_envio_id;
  if not found then
    raise exception 'El envío % no existe', p_envio_id using errcode = 'DT404';
  end if;

  select * into v_viaje from viajes where viaje_id = v_envio.envio_viaje_id for update;
  if v_viaje.viaje_estado <> 'ABIERTO' then
    raise exception 'Solo se pueden anular envíos de un viaje abierto' using errcode = 'DT409';
  end if;

  select * into v_envio from viaje_envios where envio_id = p_envio_id for update;
  if v_envio.envio_anulado then
    raise exception 'El envío % del viaje #% ya fue anulado', v_envio.envio_numero, v_viaje.viaje_id
      using errcode = 'DT409';
  end if;

  update viaje_envios set envio_anulado = true where envio_id = p_envio_id returning * into v_envio;

  v_ref := format('VIAJE #%s · ANULA %s', v_viaje.viaje_id,
                  case when v_envio.envio_numero = 1 then 'CARGA INICIAL' else 'ENVÍO ' || v_envio.envio_numero end);
  for v_item in
    select detalle_producto_id, detalle_cantidad
      from viaje_envio_detalle
     where detalle_envio_id = p_envio_id
     order by detalle_producto_id
  loop
    perform fn_mover_stock(v_item.detalle_producto_id, v_item.detalle_cantidad, 'RETORNO_VIAJE', v_ref);
  end loop;

  return next v_envio;
end;
$$;

-- ---------------------------------------------------------------------
-- 4. Liquidar: lo que anotó el jefe en su hoja
-- ---------------------------------------------------------------------
-- p_ventas:   [{"producto_id": 1, "sede_id": 2, "cantidad": 20}, ...]
-- p_retornos: [{"producto_id": 1, "devuelto": 8, "merma": 1, "motivo": "ROTURA"}, ...]
create or replace function public.fn_viaje_liquidar(
  p_viaje_id    integer,
  p_empleado_id integer,
  p_ventas      jsonb,
  p_retornos    jsonb,
  p_observacion varchar default null
) returns setof public.viajes
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_viaje       viajes%rowtype;
  v_ventas      jsonb := coalesce(p_ventas, '[]'::jsonb);
  v_retornos    jsonb := coalesce(p_retornos, '[]'::jsonb);
  v_observacion varchar := upper(nullif(trim(p_observacion), ''));
  v_ajeno       varchar;
  v_item        record;
begin
  select * into v_viaje from viajes where viaje_id = p_viaje_id for update;
  if not found then
    raise exception 'El viaje % no existe', p_viaje_id using errcode = 'DT404';
  end if;
  if v_viaje.viaje_estado <> 'ABIERTO' then
    raise exception 'El viaje #% ya fue liquidado', p_viaje_id using errcode = 'DT409';
  end if;
  if jsonb_typeof(v_ventas) <> 'array' or jsonb_typeof(v_retornos) <> 'array' then
    raise exception 'Las ventas y los retornos deben enviarse como listas' using errcode = 'DT422';
  end if;

  if exists (select 1
               from jsonb_to_recordset(v_ventas) as x (producto_id integer, sede_id integer, cantidad integer)
              where x.producto_id is null or x.sede_id is null or x.cantidad is null or x.cantidad < 0) then
    raise exception 'Cada venta debe indicar producto, ciudad y una cantidad de 0 o más' using errcode = 'DT422';
  end if;
  if exists (select 1
               from jsonb_to_recordset(v_retornos) as x (producto_id integer, devuelto integer, merma integer)
              where x.producto_id is null or coalesce(x.devuelto, 0) < 0 or coalesce(x.merma, 0) < 0) then
    raise exception 'Lo que regresó y la merma deben ser 0 o más' using errcode = 'DT422';
  end if;
  if exists (select 1
               from jsonb_to_recordset(v_retornos) as x (merma integer, motivo varchar)
              where coalesce(x.merma, 0) > 0 and nullif(trim(x.motivo), '') is null) then
    raise exception 'Indique el motivo de la merma (rotura, regalo, degustación…)' using errcode = 'DT422';
  end if;

  if exists (select 1
               from jsonb_to_recordset(v_ventas) as x (sede_id integer, cantidad integer)
               left join sedes s on s.sede_id = x.sede_id
              where x.cantidad > 0 and (s.sede_id is null or s.sede_es_almacen)) then
    raise exception 'Las ventas del viaje deben ser en una ciudad registrada y distinta del almacén'
      using errcode = 'DT422';
  end if;

  -- Solo se declara lo que se llevó (envíos no anulados)
  select p.producto_nombre || ' ' || pr.presentacion_nombre
    into v_ajeno
    from (select x.producto_id from jsonb_to_recordset(v_ventas) as x (producto_id integer, cantidad integer)
           where x.cantidad > 0
          union
          select x.producto_id from jsonb_to_recordset(v_retornos) as x (producto_id integer, devuelto integer, merma integer)
           where coalesce(x.devuelto, 0) + coalesce(x.merma, 0) > 0) d
    join productos p       on p.producto_id = d.producto_id
    join presentaciones pr on pr.presentacion_id = p.producto_presentacion_id
   where d.producto_id not in (select det.detalle_producto_id
                                 from viaje_envio_detalle det
                                 join viaje_envios e on e.envio_id = det.detalle_envio_id
                                where e.envio_viaje_id = p_viaje_id and not e.envio_anulado)
   limit 1;
  if found then
    raise exception '"%" no se llevó en el viaje #%', v_ajeno, p_viaje_id using errcode = 'DT422';
  end if;

  insert into viaje_ventas (venta_viaje_id, venta_sede_id, venta_producto_id, venta_cantidad)
  select p_viaje_id, x.sede_id, x.producto_id, sum(x.cantidad)::integer
    from jsonb_to_recordset(v_ventas) as x (producto_id integer, sede_id integer, cantidad integer)
   where x.cantidad > 0
   group by x.sede_id, x.producto_id;

  insert into viaje_retornos (retorno_viaje_id, retorno_producto_id, retorno_cantidad, retorno_merma,
                              retorno_motivo_merma)
  select p_viaje_id, x.producto_id, sum(coalesce(x.devuelto, 0))::integer, sum(coalesce(x.merma, 0))::integer,
         upper(max(nullif(trim(x.motivo), '')))
    from jsonb_to_recordset(v_retornos) as x (producto_id integer, devuelto integer, merma integer, motivo varchar)
   group by x.producto_id
  having sum(coalesce(x.devuelto, 0)) + sum(coalesce(x.merma, 0)) > 0;

  if v_observacion is null
     and exists (select 1 from fn_viaje_productos(p_viaje_id) where diferencia <> 0) then
    raise exception 'Lo declarado no cuadra con lo que se llevó. Escriba una observación para cerrar el viaje con diferencia'
      using errcode = 'DT422';
  end if;

  for v_item in
    select retorno_producto_id, retorno_cantidad
      from viaje_retornos
     where retorno_viaje_id = p_viaje_id and retorno_cantidad > 0
     order by retorno_producto_id
  loop
    perform fn_mover_stock(v_item.retorno_producto_id, v_item.retorno_cantidad, 'RETORNO_VIAJE',
                           format('VIAJE #%s · RETORNO', p_viaje_id));
  end loop;

  update viajes
     set viaje_estado            = 'LIQUIDADO',
         viaje_fecha_liquidacion = now(),
         viaje_liquidado_por     = p_empleado_id,
         viaje_observacion       = v_observacion
   where viaje_id = p_viaje_id
  returning * into v_viaje;

  return next v_viaje;
end;
$$;

-- ---------------------------------------------------------------------
-- 5. Consultas para las pantallas
-- ---------------------------------------------------------------------
-- Por producto: llevó (envíos no anulados), vendió, regresó, merma y diferencia
create or replace function public.fn_viaje_productos(p_viaje_id integer)
returns table (
  producto_id integer, producto_nombre varchar, presentacion_nombre varchar, presentacion_unidades_caja integer,
  tipo_producto_nombre varchar, llevado integer, vendido integer, devuelto integer, merma integer,
  motivo_merma varchar, diferencia integer
)
language sql stable
set search_path = public, pg_temp
as $$
  with llevado as (
    select det.detalle_producto_id as producto_id, sum(det.detalle_cantidad)::integer as cantidad
      from viaje_envio_detalle det
      join viaje_envios e on e.envio_id = det.detalle_envio_id
     where e.envio_viaje_id = p_viaje_id and not e.envio_anulado
     group by det.detalle_producto_id
  ), vendido as (
    select venta_producto_id as producto_id, sum(venta_cantidad)::integer as cantidad
      from viaje_ventas
     where venta_viaje_id = p_viaje_id
     group by venta_producto_id
  ), productos_viaje as (
    select producto_id from llevado
    union select producto_id from vendido
    union select retorno_producto_id from viaje_retornos where retorno_viaje_id = p_viaje_id
  )
  select p.producto_id, p.producto_nombre, pr.presentacion_nombre, pr.presentacion_unidades_caja,
         t.tipo_producto_nombre,
         coalesce(l.cantidad, 0), coalesce(v.cantidad, 0),
         coalesce(r.retorno_cantidad, 0), coalesce(r.retorno_merma, 0), r.retorno_motivo_merma,
         coalesce(l.cantidad, 0) - coalesce(v.cantidad, 0) - coalesce(r.retorno_cantidad, 0) - coalesce(r.retorno_merma, 0)
    from productos_viaje pv
    join productos p       on p.producto_id = pv.producto_id
    join presentaciones pr on pr.presentacion_id = p.producto_presentacion_id
    join tipo_productos t  on t.tipo_producto_id = p.producto_tipo_id
    left join llevado l    on l.producto_id = pv.producto_id
    left join vendido v    on v.producto_id = pv.producto_id
    left join viaje_retornos r on r.retorno_viaje_id = p_viaje_id and r.retorno_producto_id = pv.producto_id
   order by t.tipo_producto_nombre, p.producto_nombre, pr.presentacion_orden;
$$;

-- Lista de viajes con sus totales. El viaje no tiene fecha de regreso:
-- "días" cuenta hasta hoy mientras está abierto y hasta la liquidación al cerrarse.
create or replace function public.fn_viajes_listar(p_estado varchar default null)
returns table (
  viaje_id integer, viaje_fecha_salida timestamptz, viaje_estado varchar, viaje_fecha_liquidacion timestamptz,
  dias integer, ciudades text, envios integer, llevado integer, vendido integer, devuelto integer,
  merma integer, diferencia integer, viaje_observacion varchar, registrado_por varchar
)
language sql stable
set search_path = public, pg_temp
as $$
  select v.viaje_id, v.viaje_fecha_salida, v.viaje_estado, v.viaje_fecha_liquidacion,
         ((coalesce(v.viaje_fecha_liquidacion, now()) at time zone 'America/Lima')::date
           - (v.viaje_fecha_salida at time zone 'America/Lima')::date),
         c.ciudades, c.envios,
         coalesce(t.llevado, 0), coalesce(t.vendido, 0), coalesce(t.devuelto, 0), coalesce(t.merma, 0),
         coalesce(t.diferencia, 0),
         v.viaje_observacion, emp.empleado_nombre_completo
    from viajes v
    join empleados emp on emp.empleado_id = v.viaje_empleado_id
    left join lateral (
      select string_agg(distinct s.sede_nombre, ', ') as ciudades,
             count(distinct e.envio_id)::integer as envios
        from viaje_envios e
        join sedes s on s.sede_id = e.envio_sede_id
       where e.envio_viaje_id = v.viaje_id and not e.envio_anulado
    ) c on true
    left join lateral (
      select sum(vp.llevado)::integer as llevado, sum(vp.vendido)::integer as vendido,
             sum(vp.devuelto)::integer as devuelto, sum(vp.merma)::integer as merma,
             sum(abs(vp.diferencia))::integer as diferencia
        from fn_viaje_productos(v.viaje_id) vp
    ) t on true
   where p_estado is null or v.viaje_estado = upper(p_estado)
   order by v.viaje_fecha_salida desc, v.viaje_id desc;
$$;

-- Envíos del viaje, una fila por producto enviado
create or replace function public.fn_viaje_envios(p_viaje_id integer)
returns table (
  envio_id integer, envio_numero integer, envio_fecha timestamptz, sede_id integer, sede_nombre varchar,
  envio_referencia varchar, envio_anulado boolean, producto_id integer, producto_nombre varchar,
  presentacion_nombre varchar, presentacion_unidades_caja integer, cantidad integer
)
language sql stable
set search_path = public, pg_temp
as $$
  select e.envio_id, e.envio_numero, e.envio_fecha, s.sede_id, s.sede_nombre, e.envio_referencia,
         e.envio_anulado, p.producto_id, p.producto_nombre, pr.presentacion_nombre,
         pr.presentacion_unidades_caja, d.detalle_cantidad
    from viaje_envios e
    join sedes s               on s.sede_id = e.envio_sede_id
    join viaje_envio_detalle d on d.detalle_envio_id = e.envio_id
    join productos p           on p.producto_id = d.detalle_producto_id
    join presentaciones pr     on pr.presentacion_id = p.producto_presentacion_id
   where e.envio_viaje_id = p_viaje_id
   order by e.envio_numero, p.producto_nombre, pr.presentacion_orden;
$$;

-- Lo vendido por ciudad
create or replace function public.fn_viaje_ventas(p_viaje_id integer)
returns table (sede_id integer, sede_nombre varchar, producto_id integer, cantidad integer)
language sql stable
set search_path = public, pg_temp
as $$
  select s.sede_id, s.sede_nombre, vv.venta_producto_id, vv.venta_cantidad
    from viaje_ventas vv
    join sedes s on s.sede_id = vv.venta_sede_id
   where vv.venta_viaje_id = p_viaje_id
   order by s.sede_nombre, vv.venta_producto_id;
$$;

-- ---------------------------------------------------------------------
-- 6. Kardex: los movimientos de un viaje no se anulan desde ahí, porque
--    descuadrarían el viaje (se corrigen con fn_viaje_anular_envio).
--    Misma función existente con esa validación agregada.
-- ---------------------------------------------------------------------
create or replace function public.fn_anular_movimiento(p_movimiento_id integer)
returns public.movimientos_inventario
language plpgsql
as $$
declare
    v_mov movimientos_inventario;
    v_ref varchar := 'ANULA MOV #' || p_movimiento_id;
begin
    select * into v_mov
    from movimientos_inventario
    where movimiento_id = p_movimiento_id;

    if not found then
        raise exception 'El movimiento % no existe', p_movimiento_id;
    end if;

    if v_mov.movimiento_tipo = 'ANULACION' then
        raise exception 'No se puede anular una anulación';
    end if;

    if v_mov.movimiento_tipo in ('SALIDA_VIAJE', 'RETORNO_VIAJE') then
        raise exception 'Los movimientos de un viaje se corrigen desde la pestaña Viajes';
    end if;

    if exists (select 1 from movimientos_inventario
               where movimiento_tipo = 'ANULACION' and movimiento_referencia = v_ref) then
        raise exception 'El movimiento % ya fue anulado', p_movimiento_id;
    end if;

    -- Revierte el efecto original (lo que sumó se resta y viceversa)
    return fn_mover_stock(
        v_mov.movimiento_producto_id,
        v_mov.movimiento_stock_previo - v_mov.movimiento_stock_posterior,
        'ANULACION',
        v_ref
    );
end;
$$;

-- ---------------------------------------------------------------------
-- Seguridad: solo el backend (rol postgres) ejecuta estas funciones
-- ---------------------------------------------------------------------
do $$
declare
  f text;
begin
  foreach f in array array[
    'fn_viaje_validar_envio(integer, jsonb)',
    'fn_viaje_registrar_envio(integer, integer, integer, jsonb, varchar)',
    'fn_viaje_abrir(integer, integer, jsonb, varchar)',
    'fn_viaje_enviar(integer, integer, integer, jsonb, varchar)',
    'fn_viaje_anular_envio(integer)',
    'fn_viaje_liquidar(integer, integer, jsonb, jsonb, varchar)',
    'fn_viaje_productos(integer)',
    'fn_viajes_listar(varchar)',
    'fn_viaje_envios(integer)',
    'fn_viaje_ventas(integer)'
  ] loop
    execute format('revoke execute on function public.%s from public', f);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke execute on function public.%s from anon, authenticated', f);
    end if;
  end loop;
end $$;
