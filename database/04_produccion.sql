-- =====================================================================
-- D'Tulia · CAPA DE DATOS · 04 · Envíos de producción (fábrica → almacén)
-- ---------------------------------------------------------------------
-- Los trabajadores de la fábrica hacen, embotellan y encajan; lo anotan
-- en un cuaderno. La administradora de la fábrica lo pasa al sistema y la
-- del almacén confirma lo que realmente llegó:
--   fn_produccion_registrar  envío EN_CAMINO (el stock todavía no cambia)
--   fn_produccion_recibir    lo que llegó → ENTRADA_PRODUCCION (suma al
--                            almacén). Si no coincide con lo enviado, exige
--                            una observación.
--   fn_produccion_anular     envío registrado por error (solo EN_CAMINO)
-- Requiere 01, 02 y 03. Es idempotente.
-- =====================================================================

set search_path = public, extensions;

-- ---------------------------------------------------------------------
-- 1. Tablas
-- ---------------------------------------------------------------------
create table if not exists public.producciones (
  produccion_id           integer generated by default as identity primary key,
  produccion_fecha_envio  timestamptz not null default now(),
  produccion_enviado_por  integer not null references public.empleados (empleado_id),
  produccion_referencia   varchar(100),
  produccion_estado       varchar(15) not null default 'EN_CAMINO'
                          constraint chk_produccion_estado check (produccion_estado in ('EN_CAMINO', 'RECIBIDO', 'ANULADO')),
  -- Quién y cuándo lo recibió (o lo anuló)
  produccion_fecha_cierre timestamptz,
  produccion_cerrado_por  integer references public.empleados (empleado_id),
  produccion_observacion  varchar(300)
);
create index if not exists idx_producciones_estado on public.producciones (produccion_estado, produccion_fecha_envio);
create index if not exists idx_producciones_enviado_por on public.producciones (produccion_enviado_por);
create index if not exists idx_producciones_cerrado_por on public.producciones (produccion_cerrado_por);

create table if not exists public.produccion_detalle (
  detalle_produccion_id integer not null references public.producciones (produccion_id),
  detalle_producto_id   integer not null references public.productos (producto_id),
  detalle_enviado       integer not null constraint chk_produccion_enviado check (detalle_enviado > 0),
  -- null mientras el envío está en camino
  detalle_recibido      integer constraint chk_produccion_recibido check (detalle_recibido >= 0),
  primary key (detalle_produccion_id, detalle_producto_id)
);
create index if not exists idx_produccion_detalle_producto on public.produccion_detalle (detalle_producto_id);

-- Sin políticas: solo el backend (rol postgres) accede, igual que al resto de tablas
alter table public.producciones       enable row level security;
alter table public.produccion_detalle enable row level security;

-- ---------------------------------------------------------------------
-- 2. Registrar (fábrica) y recibir (almacén)
-- ---------------------------------------------------------------------
-- p_items: [{"producto_id": 1, "cantidad": 240}, ...] en unidades
create or replace function public.fn_produccion_registrar(
  p_empleado_id integer,
  p_items       jsonb,
  p_referencia  varchar default null
) returns setof public.producciones
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_solicitados integer;
  v_existentes  integer;
  v_produccion  producciones%rowtype;
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'El envío de producción debe incluir al menos un producto' using errcode = 'DT422';
  end if;
  if exists (select 1
               from jsonb_to_recordset(p_items) as x (producto_id integer, cantidad integer)
              where x.producto_id is null or x.cantidad is null or x.cantidad <= 0) then
    raise exception 'Cada producto debe tener una cantidad mayor a 0' using errcode = 'DT422';
  end if;

  select count(distinct x.producto_id), count(distinct p.producto_id)
    into v_solicitados, v_existentes
    from jsonb_to_recordset(p_items) as x (producto_id integer)
    left join productos p on p.producto_id = x.producto_id;
  if v_existentes <> v_solicitados then
    raise exception 'Uno o más productos del envío no existen' using errcode = 'DT404';
  end if;

  insert into producciones (produccion_enviado_por, produccion_referencia)
  values (p_empleado_id, upper(nullif(trim(p_referencia), '')))
  returning * into v_produccion;

  insert into produccion_detalle (detalle_produccion_id, detalle_producto_id, detalle_enviado)
  select v_produccion.produccion_id, x.producto_id, sum(x.cantidad)::integer
    from jsonb_to_recordset(p_items) as x (producto_id integer, cantidad integer)
   group by x.producto_id;

  return next v_produccion;
end;
$$;

-- p_items: lo que llegó, [{"producto_id": 1, "cantidad": 228}, ...]. Un producto
-- del envío que no venga en la lista se toma como 0 (no llegó nada).
create or replace function public.fn_produccion_recibir(
  p_produccion_id integer,
  p_empleado_id   integer,
  p_items         jsonb,
  p_observacion   varchar default null
) returns setof public.producciones
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_produccion  producciones%rowtype;
  v_items       jsonb := coalesce(p_items, '[]'::jsonb);
  v_observacion varchar := upper(nullif(trim(p_observacion), ''));
  v_item        record;
begin
  select * into v_produccion from producciones where produccion_id = p_produccion_id for update;
  if not found then
    raise exception 'El envío de producción % no existe', p_produccion_id using errcode = 'DT404';
  end if;
  if v_produccion.produccion_estado <> 'EN_CAMINO' then
    raise exception 'El envío de producción #% ya fue %', p_produccion_id,
      case v_produccion.produccion_estado when 'RECIBIDO' then 'recibido' else 'anulado' end
      using errcode = 'DT409';
  end if;
  if jsonb_typeof(v_items) <> 'array' then
    raise exception 'Lo recibido debe enviarse como lista' using errcode = 'DT422';
  end if;
  if exists (select 1
               from jsonb_to_recordset(v_items) as x (producto_id integer, cantidad integer)
              where x.producto_id is null or x.cantidad is null or x.cantidad < 0) then
    raise exception 'Lo recibido debe ser 0 o más' using errcode = 'DT422';
  end if;
  if exists (select 1
               from jsonb_to_recordset(v_items) as x (producto_id integer)
              where x.producto_id not in (select detalle_producto_id from produccion_detalle
                                           where detalle_produccion_id = p_produccion_id)) then
    raise exception 'Hay productos que no están en el envío #%. Regístrelos con una entrada de stock', p_produccion_id
      using errcode = 'DT422';
  end if;

  update produccion_detalle d
     set detalle_recibido = coalesce((select sum(x.cantidad)::integer
                                        from jsonb_to_recordset(v_items) as x (producto_id integer, cantidad integer)
                                       where x.producto_id = d.detalle_producto_id), 0)
   where d.detalle_produccion_id = p_produccion_id;

  if v_observacion is null
     and exists (select 1 from produccion_detalle
                  where detalle_produccion_id = p_produccion_id and detalle_recibido <> detalle_enviado) then
    raise exception 'Lo recibido no coincide con lo que envió la fábrica. Escriba una observación para confirmar con diferencia'
      using errcode = 'DT422';
  end if;

  for v_item in
    select detalle_producto_id, detalle_recibido
      from produccion_detalle
     where detalle_produccion_id = p_produccion_id and detalle_recibido > 0
     order by detalle_producto_id
  loop
    perform fn_mover_stock(v_item.detalle_producto_id, v_item.detalle_recibido, 'ENTRADA_PRODUCCION',
                           format('PRODUCCIÓN #%s', p_produccion_id));
  end loop;

  update producciones
     set produccion_estado       = 'RECIBIDO',
         produccion_fecha_cierre = now(),
         produccion_cerrado_por  = p_empleado_id,
         produccion_observacion  = v_observacion
   where produccion_id = p_produccion_id
  returning * into v_produccion;

  return next v_produccion;
end;
$$;

create or replace function public.fn_produccion_anular(
  p_produccion_id integer,
  p_empleado_id   integer,
  p_observacion   varchar default null
) returns setof public.producciones
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_produccion producciones%rowtype;
begin
  select * into v_produccion from producciones where produccion_id = p_produccion_id for update;
  if not found then
    raise exception 'El envío de producción % no existe', p_produccion_id using errcode = 'DT404';
  end if;
  if v_produccion.produccion_estado <> 'EN_CAMINO' then
    raise exception 'Solo se puede anular un envío que sigue en camino' using errcode = 'DT409';
  end if;

  update producciones
     set produccion_estado       = 'ANULADO',
         produccion_fecha_cierre = now(),
         produccion_cerrado_por  = p_empleado_id,
         produccion_observacion  = upper(nullif(trim(p_observacion), ''))
   where produccion_id = p_produccion_id
  returning * into v_produccion;

  return next v_produccion;
end;
$$;

-- ---------------------------------------------------------------------
-- 3. Consultas para las pantallas
-- ---------------------------------------------------------------------
create or replace function public.fn_produccion_productos(p_produccion_id integer)
returns table (
  producto_id integer, producto_nombre varchar, presentacion_nombre varchar, presentacion_unidades_caja integer,
  tipo_producto_nombre varchar, enviado integer, recibido integer, diferencia integer
)
language sql stable
set search_path = public, pg_temp
as $$
  select p.producto_id, p.producto_nombre, pr.presentacion_nombre, pr.presentacion_unidades_caja,
         t.tipo_producto_nombre, d.detalle_enviado, d.detalle_recibido,
         d.detalle_enviado - d.detalle_recibido
    from produccion_detalle d
    join productos p       on p.producto_id = d.detalle_producto_id
    join presentaciones pr on pr.presentacion_id = p.producto_presentacion_id
    join tipo_productos t  on t.tipo_producto_id = p.producto_tipo_id
   where d.detalle_produccion_id = p_produccion_id
   order by t.tipo_producto_nombre, p.producto_nombre, pr.presentacion_orden;
$$;

-- "días": cuánto lleva en camino (hasta hoy) o cuánto tardó en recibirse
create or replace function public.fn_producciones_listar(p_estado varchar default null)
returns table (
  produccion_id integer, produccion_fecha_envio timestamptz, produccion_estado varchar,
  produccion_fecha_cierre timestamptz, dias integer, enviado_por varchar, cerrado_por varchar,
  produccion_referencia varchar, productos integer, enviado integer, recibido integer, diferencia integer,
  produccion_observacion varchar
)
language sql stable
set search_path = public, pg_temp
as $$
  select pc.produccion_id, pc.produccion_fecha_envio, pc.produccion_estado, pc.produccion_fecha_cierre,
         ((coalesce(pc.produccion_fecha_cierre, now()) at time zone 'America/Lima')::date
           - (pc.produccion_fecha_envio at time zone 'America/Lima')::date),
         env.empleado_nombre_completo, cer.empleado_nombre_completo, pc.produccion_referencia,
         t.productos, t.enviado, t.recibido, t.diferencia, pc.produccion_observacion
    from producciones pc
    join empleados env      on env.empleado_id = pc.produccion_enviado_por
    left join empleados cer on cer.empleado_id = pc.produccion_cerrado_por
    left join lateral (
      select count(*)::integer as productos, sum(d.detalle_enviado)::integer as enviado,
             sum(d.detalle_recibido)::integer as recibido,
             sum(abs(d.detalle_enviado - d.detalle_recibido))::integer as diferencia
        from produccion_detalle d
       where d.detalle_produccion_id = pc.produccion_id
    ) t on true
   where p_estado is null or pc.produccion_estado = upper(p_estado)
   order by pc.produccion_fecha_envio desc, pc.produccion_id desc;
$$;

-- ---------------------------------------------------------------------
-- Seguridad: solo el backend (rol postgres) ejecuta estas funciones
-- ---------------------------------------------------------------------
do $$
declare
  f text;
begin
  foreach f in array array[
    'fn_produccion_registrar(integer, jsonb, varchar)',
    'fn_produccion_recibir(integer, integer, jsonb, varchar)',
    'fn_produccion_anular(integer, integer, varchar)',
    'fn_produccion_productos(integer)',
    'fn_producciones_listar(varchar)'
  ] loop
    execute format('revoke execute on function public.%s from public', f);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke execute on function public.%s from anon, authenticated', f);
    end if;
  end loop;
end $$;
